-- ============================================================================
-- Mahfooz Mobile — PostgreSQL schema
-- CY321 Secure Software Design (Project ID 32106)
--
-- Models every entity described in the project concept document, plus a
-- PTA type-approved IMEI registry. Core rule enforced here:
--   *** A device (IMEI) may be linked to a user's CNIC ONLY if that IMEI is
--       present and active in the PTA-approved registry. ***
--
-- Target: PostgreSQL 14+.  Load with:  psql -d mahfooz -f 01_schema.sql
-- ============================================================================

SET client_encoding = 'UTF8';

BEGIN;

-- pgcrypto gives us: digest()/hmac() (hashing, blind indexes, audit chain),
-- pgp_sym_encrypt()/pgp_sym_decrypt() (AES column encryption at rest),
-- crypt()/gen_salt() (password hashing stand-in).
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------------
-- Enumerated domains
-- ---------------------------------------------------------------------------
CREATE TYPE user_role     AS ENUM ('citizen', 'agent', 'auditor', 'system');
CREATE TYPE device_status AS ENUM ('active', 'temp_blocked', 'blocked', 'retired');
CREATE TYPE block_state   AS ENUM ('none', 'temporary', 'full');
CREATE TYPE review_status AS ENUM ('auto-approved', 'manual-review',
                                   'manual-review-required', 'fully-verified');
CREATE TYPE risk_level    AS ENUM ('low', 'medium', 'high');
CREATE TYPE otp_purpose   AS ENUM ('emergency_report', 'pin_recovery');

-- ---------------------------------------------------------------------------
-- Helper functions
-- ---------------------------------------------------------------------------

-- IMEI Luhn checksum (concept: input validation = 15 digits + Luhn).
CREATE OR REPLACE FUNCTION is_luhn_valid(num text) RETURNS boolean AS $$
DECLARE s int := 0; d int; i int; alt boolean := false;
BEGIN
  IF num IS NULL OR num !~ '^\d+$' THEN RETURN false; END IF;
  FOR i IN REVERSE length(num)..1 LOOP
    d := substr(num, i, 1)::int;
    IF alt THEN d := d * 2; IF d > 9 THEN d := d - 9; END IF; END IF;
    s := s + d;
    alt := NOT alt;
  END LOOP;
  RETURN s % 10 = 0;
END; $$ LANGUAGE plpgsql IMMUTABLE;

-- CNIC format check (00000-0000000-0).
CREATE OR REPLACE FUNCTION is_cnic_format(c text) RETURNS boolean AS $$
  SELECT c ~ '^\d{5}-\d{7}-\d$';
$$ LANGUAGE sql IMMUTABLE;

-- CNIC mask for UI (keeps first group + last digit, hides the middle).
CREATE OR REPLACE FUNCTION mask_cnic(c text) RETURNS text AS $$
  SELECT CASE WHEN c ~ '^\d{5}-\d{7}-\d$'
    THEN split_part(c,'-',1) || '-' || repeat('•', 7) || '-' || split_part(c,'-',3)
    ELSE c END;
$$ LANGUAGE sql IMMUTABLE;

-- ---------------------------------------------------------------------------
-- PTA type-approved IMEI registry  (the whitelist)
-- ---------------------------------------------------------------------------
CREATE TABLE pta_approved_imei (
  imei         char(15) PRIMARY KEY
                 CHECK (imei ~ '^\d{15}$' AND is_luhn_valid(imei)),
  brand        text,
  model        text,
  approval_ref text        NOT NULL,                 -- PTA type-approval reference
  approved_on  date        NOT NULL DEFAULT current_date,
  is_active    boolean     NOT NULL DEFAULT true     -- an approval can be revoked
);
COMMENT ON TABLE pta_approved_imei IS
  'PTA type-approved IMEIs. A device may only be registered against a CNIC if its IMEI is here AND is_active.';

-- ---------------------------------------------------------------------------
-- Accounts (citizens + staff). Identifying fields are AES-encrypted at rest
-- (pgp_sym_encrypt); low-sensitivity masked forms are kept in the clear for UI,
-- and HMAC "blind indexes" allow uniqueness / lookup without the plaintext.
-- ---------------------------------------------------------------------------
CREATE TABLE account (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role               user_role   NOT NULL,
  full_name          text        NOT NULL,
  initials           text,

  -- Encrypted identifiers (ciphertext at rest):
  cnic_enc           bytea,
  phone_enc          bytea,
  email_enc          bytea,
  alt_phone_enc      bytea,

  -- Blind indexes (deterministic HMAC) for uniqueness + lookup:
  cnic_bidx          text UNIQUE,   -- CNIC-to-account uniqueness (concept 1a)
  phone_bidx         text,          -- login / emergency lookup by phone

  -- Masked forms for display (not sensitive):
  cnic_masked        text,
  phone_masked       text,

  -- Credentials (hashes/secrets only — never plaintext):
  password_hash      text NOT NULL,       -- Argon2id at app layer (bcrypt here)
  emergency_pin_hash text,                -- memorised Emergency PIN (hash only)
  physical_code_hash text,                -- paper recovery code (hash only)
  totp_secret_enc    bytea,               -- TOTP shared secret, encrypted at rest

  created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_account_phone_bidx ON account(phone_bidx);

-- 5 personal recovery questions per account; answers stored hashed + normalised.
CREATE TABLE account_recovery_question (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id  bigint NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  position    int    NOT NULL CHECK (position BETWEEN 1 AND 5),
  question    text   NOT NULL,
  answer_hash text   NOT NULL,
  UNIQUE (account_id, position)
);

-- ---------------------------------------------------------------------------
-- Devices — one row per registered IMEI, owned by one account.
-- The IMEI MUST exist in pta_approved_imei (FK) and be active (trigger below).
-- ---------------------------------------------------------------------------
CREATE TABLE device (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id    bigint   NOT NULL REFERENCES account(id),
  imei          char(15) NOT NULL UNIQUE
                  REFERENCES pta_approved_imei(imei),   -- only approved IMEIs
  nickname      text,
  brand         text,
  model         text,
  status        device_status NOT NULL DEFAULT 'active',
  registered_at timestamptz   NOT NULL DEFAULT now(),
  CHECK (imei ~ '^\d{15}$' AND is_luhn_valid(imei))
);

-- The FK guarantees the IMEI is *approved*; this trigger additionally refuses
-- IMEIs whose approval has been *revoked* (is_active = false).
CREATE OR REPLACE FUNCTION trg_require_active_approval() RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pta_approved_imei p
                 WHERE p.imei = NEW.imei AND p.is_active) THEN
    RAISE EXCEPTION
      'IMEI % is not an active PTA-approved device and cannot be linked to a CNIC',
      NEW.imei USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER device_require_active_approval
  BEFORE INSERT OR UPDATE OF imei ON device
  FOR EACH ROW EXECUTE FUNCTION trg_require_active_approval();

-- ---------------------------------------------------------------------------
-- Theft cases (FIR records) + their timelines
-- ---------------------------------------------------------------------------
CREATE TABLE theft_case (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref            text        NOT NULL UNIQUE,
  device_id      bigint      NOT NULL REFERENCES device(id),
  account_id     bigint      NOT NULL REFERENCES account(id),
  created_at     timestamptz NOT NULL DEFAULT now(),
  police_station text,
  district       text        DEFAULT 'Lahore',
  risk_level     risk_level,
  risk_matches   int,
  risk_total     int,
  risk_factors   jsonb,
  block_state    block_state   NOT NULL DEFAULT 'none',
  review_status  review_status,
  reported_via   text
);

CREATE TABLE case_timeline (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id bigint      NOT NULL REFERENCES theft_case(id) ON DELETE CASCADE,
  step    text        NOT NULL,
  at      timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Staff queue: disputes AND risk-flagged theft reviews
-- ---------------------------------------------------------------------------
CREATE TABLE dispute (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_ref      text,
  account_id    bigint REFERENCES account(id),
  citizen_label text,
  kind          text        NOT NULL DEFAULT 'dispute',  -- 'dispute' | 'theft_review'
  summary       text,
  priority      text        NOT NULL DEFAULT 'Normal',
  status        text        NOT NULL DEFAULT 'Open',
  risk_level    risk_level,
  reason        text,
  device_label  text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Notifications
-- ---------------------------------------------------------------------------
CREATE TABLE notification (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  text       text        NOT NULL,
  meta       text,
  icon       text,
  is_read    boolean     NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- One-time passcodes (emergency report confirmation + alternate PIN recovery).
-- Only a hash of the code is stored.
-- ---------------------------------------------------------------------------
CREATE TABLE otp (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  code_hash  text        NOT NULL,
  purpose    otp_purpose NOT NULL,
  issued_at  timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '10 minutes',
  consumed   boolean     NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------------
-- Sessions (concept: short-lived sessions + refresh-token rotation)
-- ---------------------------------------------------------------------------
CREATE TABLE app_session (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id         bigint      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  refresh_token_hash text        NOT NULL,
  user_agent         text,
  ip                 inet,
  created_at         timestamptz NOT NULL DEFAULT now(),
  expires_at         timestamptz NOT NULL DEFAULT now() + interval '7 days',
  revoked            boolean     NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------------
-- Duplicate-CNIC registration attempts (fraud signal for the real owner)
-- ---------------------------------------------------------------------------
CREATE TABLE cnic_registration_attempt (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cnic_bidx    text        NOT NULL,     -- blind index of the attempted CNIC
  cnic_masked  text,
  source_ip    inet,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  note         text
);

-- ---------------------------------------------------------------------------
-- Tamper-evident, append-only audit log (hash-chained).
-- entry_hash = SHA256(prev_hash | ts | actor | action | ref). The trigger
-- fills prev_hash + entry_hash automatically, so the chain can't be skipped.
-- ---------------------------------------------------------------------------
CREATE TABLE audit_log (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts                 timestamptz NOT NULL DEFAULT now(),
  actor              text        NOT NULL,
  action             text        NOT NULL,
  ref                text,
  ip                 inet,
  device_fingerprint text,
  prev_hash          text        NOT NULL,
  entry_hash         text        NOT NULL
);

CREATE OR REPLACE FUNCTION trg_audit_chain() RETURNS trigger AS $$
DECLARE last_hash text;
BEGIN
  SELECT entry_hash INTO last_hash FROM audit_log ORDER BY id DESC LIMIT 1;
  IF last_hash IS NULL THEN last_hash := 'GENESIS'; END IF;
  NEW.prev_hash := last_hash;
  NEW.entry_hash := encode(digest(
      last_hash || '|' || NEW.ts::text || '|' || NEW.actor || '|' ||
      NEW.action || '|' || coalesce(NEW.ref, ''), 'sha256'), 'hex');
  RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER audit_log_chain BEFORE INSERT ON audit_log
  FOR EACH ROW EXECUTE FUNCTION trg_audit_chain();

-- Recompute the chain and report the first broken row (if any).
CREATE OR REPLACE FUNCTION verify_audit_chain()
  RETURNS TABLE(ok boolean, broken_at bigint, entries bigint) AS $$
DECLARE r record; prev text := 'GENESIS'; calc text; n bigint := 0;
BEGIN
  FOR r IN SELECT * FROM audit_log ORDER BY id LOOP
    n := n + 1;
    calc := encode(digest(prev || '|' || r.ts::text || '|' || r.actor || '|' ||
                          r.action || '|' || coalesce(r.ref,''), 'sha256'), 'hex');
    IF r.prev_hash <> prev OR r.entry_hash <> calc THEN
      RETURN QUERY SELECT false, r.id, n; RETURN;
    END IF;
    prev := r.entry_hash;
  END LOOP;
  RETURN QUERY SELECT true, NULL::bigint, n;
END; $$ LANGUAGE plpgsql;

-- Append-only: block UPDATE/DELETE on the log for everyone.
REVOKE UPDATE, DELETE, TRUNCATE ON audit_log FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Least-privilege DB roles (concept: separate credentials; audit writer is
-- insert-only; auditor is read-only and cannot write device/log tables).
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mahfooz_app')
    THEN CREATE ROLE mahfooz_app NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mahfooz_audit_writer')
    THEN CREATE ROLE mahfooz_audit_writer NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mahfooz_auditor')
    THEN CREATE ROLE mahfooz_auditor NOLOGIN; END IF;
END $$;

-- App role: CRUD on operational tables, but only INSERT on the audit log.
GRANT SELECT, INSERT, UPDATE, DELETE ON
  account, account_recovery_question, device, theft_case, case_timeline,
  dispute, notification, otp, app_session, cnic_registration_attempt
  TO mahfooz_app;
GRANT SELECT ON pta_approved_imei TO mahfooz_app;   -- app checks approval, never edits it
GRANT INSERT ON audit_log TO mahfooz_app, mahfooz_audit_writer;

-- Auditor role: read-only across the log (and operational data), no writes.
GRANT SELECT ON audit_log TO mahfooz_auditor;
GRANT EXECUTE ON FUNCTION verify_audit_chain() TO mahfooz_auditor;

COMMIT;
